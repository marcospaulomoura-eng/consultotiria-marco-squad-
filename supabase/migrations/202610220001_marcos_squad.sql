-- Marcos Squad: server-only PostgreSQL schema for Supabase.
-- Apply with the database owner; the React bundle never receives DB credentials.
-- This migration has no customer/demo seed and never touches public tables.
CREATE SCHEMA IF NOT EXISTS marcos_squad;
REVOKE ALL ON SCHEMA marcos_squad FROM PUBLIC;
SET LOCAL search_path TO marcos_squad, pg_catalog;

CREATE TABLE IF NOT EXISTS metadata (key TEXT PRIMARY KEY, value TEXT NOT NULL);
INSERT INTO metadata (key, value) VALUES ('app_id', 'marcos-squad-dashboard-v1') ON CONFLICT DO NOTHING;
DO $$ BEGIN
  IF (SELECT value FROM marcos_squad.metadata WHERE key = 'app_id') IS DISTINCT FROM 'marcos-squad-dashboard-v1' THEN
    RAISE EXCEPTION 'O schema marcos_squad pertence a outra aplicação.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS clients (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL DEFAULT '',
  phone TEXT NOT NULL DEFAULT '',
  plan TEXT NOT NULL,
  service TEXT NOT NULL,
  amount_cents INTEGER NOT NULL CHECK (amount_cents >= 0),
  start_date TEXT NOT NULL,
  end_date TEXT NOT NULL,
  notes TEXT NOT NULL DEFAULT '',
  is_demo INTEGER NOT NULL DEFAULT 0 CHECK (is_demo IN (0, 1)),
  whatsapp_opt_in INTEGER NOT NULL DEFAULT 0 CHECK (whatsapp_opt_in IN (0, 1)),
  revision INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS clients_end_date ON clients(end_date);

CREATE TABLE IF NOT EXISTS activities (
  id TEXT PRIMARY KEY,
  sequence_id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  type TEXT NOT NULL,
  client_name TEXT NOT NULL,
  description TEXT NOT NULL,
  created_at TEXT NOT NULL,
  is_demo INTEGER NOT NULL DEFAULT 0 CHECK (is_demo IN (0, 1))
);
CREATE INDEX IF NOT EXISTS activities_created_at ON activities(created_at);
CREATE TABLE IF NOT EXISTS settings (id INTEGER PRIMARY KEY CHECK (id = 1), value TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS ms_sessions (
  token_hash TEXT PRIMARY KEY,
  password_version TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS ms_sessions_expiry ON ms_sessions(expires_at);
CREATE TABLE IF NOT EXISTS ms_login_attempts (ip_key TEXT PRIMARY KEY, count INTEGER NOT NULL, reset_at BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS ms_login_attempts_expiry ON ms_login_attempts(reset_at);

-- Contract snapshots deliberately survive deletion of the client, as before.
CREATE TABLE IF NOT EXISTS contracts (
  id TEXT PRIMARY KEY, client_id TEXT NOT NULL, client_name TEXT NOT NULL,
  plan TEXT NOT NULL, service TEXT NOT NULL,
  amount_cents INTEGER NOT NULL CHECK (amount_cents >= 0),
  start_date TEXT NOT NULL, end_date TEXT NOT NULL, sold_at TEXT NOT NULL,
  tracking_status TEXT NOT NULL CHECK (tracking_status IN ('pending', 'unconfirmed'))
);
CREATE INDEX IF NOT EXISTS contracts_sold_at ON contracts(sold_at);
CREATE INDEX IF NOT EXISTS contracts_client_id ON contracts(client_id);
CREATE TABLE IF NOT EXISTS payments (
  id TEXT PRIMARY KEY,
  contract_id TEXT NOT NULL REFERENCES contracts(id) ON DELETE CASCADE,
  amount_cents INTEGER NOT NULL CHECK (amount_cents > 0),
  method TEXT NOT NULL CHECK (method IN ('Pix', 'Transferência', 'Dinheiro', 'Cartão', 'Outro')),
  paid_at TEXT NOT NULL, notes TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS payments_contract_id ON payments(contract_id);
CREATE INDEX IF NOT EXISTS payments_paid_at ON payments(paid_at);

CREATE TABLE IF NOT EXISTS leads (
  id TEXT PRIMARY KEY, name TEXT NOT NULL, phone TEXT NOT NULL,
  plan TEXT NOT NULL, service TEXT NOT NULL,
  amount_cents INTEGER NOT NULL DEFAULT 0 CHECK (amount_cents >= 0),
  stage TEXT NOT NULL DEFAULT 'new' CHECK (stage IN ('new', 'contacted', 'negotiation', 'won', 'lost')),
  follow_up_at TEXT NOT NULL, notes TEXT NOT NULL DEFAULT '',
  whatsapp_opt_in INTEGER NOT NULL DEFAULT 0 CHECK (whatsapp_opt_in IN (0, 1)),
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS leads_follow_up_at ON leads(follow_up_at);
CREATE INDEX IF NOT EXISTS leads_stage ON leads(stage);
CREATE TABLE IF NOT EXISTS whatsapp_dispatches (
  dispatch_key TEXT PRIMARY KEY,
  status TEXT NOT NULL CHECK (status IN ('sending', 'sent', 'failed')),
  provider_message_id TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL, updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS fitness_access (
  client_id TEXT PRIMARY KEY REFERENCES clients(id) ON DELETE CASCADE,
  code_hash TEXT NOT NULL UNIQUE, display_name TEXT NOT NULL,
  community INTEGER NOT NULL DEFAULT 0 CHECK (community IN (0, 1)), created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS fitness_sessions (
  token_hash TEXT PRIMARY KEY,
  client_id TEXT NOT NULL REFERENCES fitness_access(client_id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS fitness_sessions_expiry ON fitness_sessions(expires_at);
CREATE TABLE IF NOT EXISTS fitness_attempts (ip_key TEXT PRIMARY KEY, count INTEGER NOT NULL, reset_at BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS fitness_attempts_expiry ON fitness_attempts(reset_at);
CREATE TABLE IF NOT EXISTS fitness_catalog (id TEXT PRIMARY KEY, kind TEXT NOT NULL CHECK (kind IN ('food', 'exercise')), data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS fitness_workouts (
  id TEXT PRIMARY KEY, client_id TEXT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  data TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS fitness_workout_client ON fitness_workouts(client_id);
CREATE TABLE IF NOT EXISTS fitness_diets (client_id TEXT PRIMARY KEY REFERENCES clients(id) ON DELETE CASCADE, data TEXT NOT NULL, updated_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS fitness_logs (
  id TEXT PRIMARY KEY, client_id TEXT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  workout_id TEXT NOT NULL, workout_name TEXT NOT NULL, day TEXT NOT NULL, created_at TEXT NOT NULL,
  UNIQUE (client_id, workout_id, day)
);
CREATE INDEX IF NOT EXISTS fitness_logs_day ON fitness_logs(day, client_id);
CREATE TABLE IF NOT EXISTS fitness_posts (
  id TEXT PRIMARY KEY,
  client_id TEXT NOT NULL REFERENCES fitness_access(client_id) ON DELETE CASCADE,
  caption TEXT NOT NULL, image TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS fitness_posts_created ON fitness_posts(created_at, id);
CREATE TABLE IF NOT EXISTS fitness_likes (
  post_id TEXT NOT NULL REFERENCES fitness_posts(id) ON DELETE CASCADE,
  client_id TEXT NOT NULL REFERENCES fitness_access(client_id) ON DELETE CASCADE,
  PRIMARY KEY (post_id, client_id)
);
CREATE TABLE IF NOT EXISTS fitness_comments (
  id TEXT PRIMARY KEY,
  post_id TEXT NOT NULL REFERENCES fitness_posts(id) ON DELETE CASCADE,
  client_id TEXT NOT NULL REFERENCES fitness_access(client_id) ON DELETE CASCADE,
  text TEXT NOT NULL, created_at TEXT NOT NULL
);

-- Only the database-owner/server connection operates this schema. It is not an
-- exposed Supabase API schema; anon/authenticated have no grants or RLS policy.
REVOKE ALL ON ALL TABLES IN SCHEMA marcos_squad FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA marcos_squad FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA marcos_squad REVOKE ALL ON TABLES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA marcos_squad REVOKE ALL ON SEQUENCES FROM PUBLIC;
DO $$
DECLARE target_role TEXT; target_table TEXT;
BEGIN
  FOREACH target_role IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = target_role) THEN
      EXECUTE format('REVOKE ALL ON SCHEMA marcos_squad FROM %I', target_role);
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA marcos_squad FROM %I', target_role);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA marcos_squad FROM %I', target_role);
    END IF;
  END LOOP;
  FOR target_table IN SELECT tablename FROM pg_tables WHERE schemaname = 'marcos_squad' LOOP
    EXECUTE format('ALTER TABLE marcos_squad.%I ENABLE ROW LEVEL SECURITY', target_table);
  END LOOP;
END $$;
